package MonteCarloMini;

public class Minimum {
    private int min;
    private int find;

    // Constructor for Minimum
    public Minimum(int min, int find) {
        this.min = min;
        this.find = find;

    }

    // get Minimum
    public int getMin() {
        return min;

    }

    // get associated finder
    public int getFinder() {
        return find;

    }
}
